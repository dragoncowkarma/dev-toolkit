function ascii(bytes, start, length) {
  return Array.from(bytes.subarray(start, start + length), (byte) =>
    byte === 0 ? '' : byte >= 32 && byte <= 126 ? String.fromCharCode(byte) : '�'
  ).join('').trimEnd();
}

/** Parse the first 0xC0 bytes of a GBA ROM. */
export function parseGbaHeader(input) {
  const bytes = input instanceof Uint8Array ? input :
    input instanceof ArrayBuffer ? new Uint8Array(input) : null;
  if (!bytes || bytes.length < 0xc0) {
    return { ok: false, error: 'A GBA header requires at least 192 bytes (0xC0).' };
  }
  const word = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).getUint32(0, true);
  const isBranch = (word & 0x0e000000) === 0x0a000000 && (word >>> 28) !== 15;
  const offset = ((word & 0xffffff) << 8 >> 8) * 4;
  const expected = (-(bytes.subarray(0xa0, 0xbd).reduce((sum, byte) => sum + byte, 0)) - 0x19)
    & 0xff;
  return {
    ok: true,
    title: ascii(bytes, 0xa0, 12),
    gameCode: ascii(bytes, 0xac, 4),
    makerCode: ascii(bytes, 0xb0, 2),
    mainUnitCode: bytes[0xb3],
    deviceType: bytes[0xb4],
    softwareVersion: bytes[0xbc],
    entry: { word, isBranch, target: (0x08000008 + offset) >>> 0,
      link: Boolean(word & 0x01000000), condition: word >>> 28 },
    logoValid: LOGO.every((byte, index) => bytes[index + 4] === byte),
    fixedByte: bytes[0xb2],
    fixedValid: bytes[0xb2] === 0x96,
    checksum: { expected, actual: bytes[0xbd], valid: expected === bytes[0xbd] },
  };
}

/** Decode explicitly selected hexadecimal or Base64 input into bytes. */
export function decodeBytes(text, format) {
  const cleaned = text.replace(/\s/g, '');
  if (format === 'hex') {
    if (!cleaned || cleaned.length % 2 || !/^[\da-f]+$/i.test(cleaned)) {
      return { ok: false, error: 'Enter complete hexadecimal byte pairs.' };
    }
    return { ok: true, bytes: Uint8Array.from(cleaned.match(/../g), (pair) => parseInt(pair, 16)) };
  }
  const base64Pattern = /^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/;
  if (!cleaned || cleaned.length % 4 || !base64Pattern.test(cleaned)) {
    return { ok: false, error: 'Enter valid Base64 bytes.' };
  }
  try {
    return { ok: true, bytes: Uint8Array.from(atob(cleaned), (char) => char.charCodeAt(0)) };
  } catch {
    return { ok: false, error: 'Enter valid Base64 bytes.' };
  }
}
